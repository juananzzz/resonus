/**
 * Config plugin: declares Resonus as a music player.
 *
 * Android's standard way to say "this is a music app" is CATEGORY_APP_MUSIC on
 * the main activity's MAIN filter. Launchers use it to find the default music
 * app, and apps such as KWGT use the same query to build their list of
 * players. Resonus already publishes a MediaSession, but that only reaches
 * apps with notification access; this is what puts it in the list at all.
 *
 * The category goes on the launcher filter itself, next to CATEGORY_LAUNCHER,
 * rather than on a second MAIN filter. A detector that walks the launcher
 * entry's categories then sees it; the previous separate filter was invisible
 * to that walk. `app.json`'s `android.intentFilters` always adds a new filter,
 * which is why this needs a plugin: android/ is regenerated by prebuild, and
 * the merge into the existing filter cannot be expressed in app.json.
 *
 * android/ is in .gitignore and regenerated by prebuild, so an edit to the
 * manifest by hand would not survive.
 */
const { AndroidConfig, withAndroidManifest } = require('@expo/config-plugins');

const ACTION_MAIN = 'android.intent.action.MAIN';
const CATEGORY_LAUNCHER = 'android.intent.category.LAUNCHER';
const CATEGORY_APP_MUSIC = 'android.intent.category.APP_MUSIC';

function names(nodes) {
  return (nodes ?? []).map((node) => node.$?.['android:name']);
}

function hasName(nodes, name) {
  return names(nodes).includes(name);
}

function mainFilter(activity) {
  const filters = activity['intent-filter'] ?? [];
  const launcher = filters.find(
    (filter) => hasName(filter.action, ACTION_MAIN) && hasName(filter.category, CATEGORY_LAUNCHER),
  );
  if (launcher) return launcher;
  const main = filters.find((filter) => hasName(filter.action, ACTION_MAIN));
  if (main) return main;
  const created = {
    action: [{ $: { 'android:name': ACTION_MAIN } }],
    category: [{ $: { 'android:name': CATEGORY_LAUNCHER } }],
  };
  activity['intent-filter'] = [...filters, created];
  return created;
}

/**
 * Adds the category in place. Returns whether anything changed, so a second
 * prebuild run is a no-op and tests can tell the two cases apart.
 */
function ensureMusicCategory(androidManifest) {
  const activity = AndroidConfig.Manifest.getMainActivityOrThrow(androidManifest);
  const filter = mainFilter(activity);
  if (hasName(filter.category, CATEGORY_APP_MUSIC)) return false;
  filter.category = [
    ...(filter.category ?? []),
    { $: { 'android:name': CATEGORY_APP_MUSIC } },
  ];
  return true;
}

module.exports = function withMusicPlayer(config) {
  return withAndroidManifest(config, (cfg) => {
    ensureMusicCategory(cfg.modResults);
    return cfg;
  });
};
module.exports.ensureMusicCategory = ensureMusicCategory;
