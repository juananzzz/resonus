/**
 * Config plugin: ProGuard keep rules for the patched expo-audio module.
 *
 * The expo-audio patch adds classes and methods that R8 cannot trace through
 * the Expo module bridge (all calls are reflective or string-keyed). Without
 * -keep rules they are silently removed or renamed in release builds, causing
 * NoSuchMethodError / NoClassDefFoundError at runtime for:
 *
 *   - expo.modules.audio.service.PreloadingBitmapLoader (artwork pre-fetch)
 *   - expo.modules.audio.service.MediaSessionPlayer (position offset/duration)
 *   - FragmentSeekingExtractor/Factory (gapless seek)
 *   - AudioPlayer: setNextSource, clearNextSource, setLockScreenFavorite,
 *     emitRemoteFavorite, emitRemoteSeek, audioSessionId
 *
 * android/ is gitignored and regenerated by prebuild, so this must be a
 * plugin: an edit to proguard-rules.pro by hand would not survive.
 */
const { withDangerousMod } = require('@expo/config-plugins');
const path = require('path');
const fs = require('fs');

const RULES = `
# expo-audio (patched) — keep patched classes so R8 does not strip them in
# release builds. All new methods are called via the Expo module bridge which
# R8 cannot trace statically.
-keep class expo.modules.audio.** { *; }
-keep class expo.modules.audio.service.** { *; }
-keepclassmembers class expo.modules.audio.AudioPlayer {
    public void setNextSource(...);
    public void clearNextSource();
    public void setLockScreenFavorite(...);
    public void emitRemoteFavorite();
    public void emitRemoteSeek(...);
    public int getAudioSessionId();
}
`;

module.exports = function withExpoAudioProguard(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const proguardPath = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'proguard-rules.pro',
      );
      const current = fs.readFileSync(proguardPath, 'utf8');
      if (!current.includes('expo-audio (patched)')) {
        fs.writeFileSync(proguardPath, current + RULES, 'utf8');
      }
      return cfg;
    },
  ]);
};
