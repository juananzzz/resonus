#!/usr/bin/env node
/**
 * Writes `src/lib/settingsIndex.generated.ts`: every setting's label and the
 * screen it lives on, for the search box at the top of Settings.
 *
 *   pnpm settings:index            write it
 *   pnpm settings:index --check    fail if it is out of date (a test runs this)
 *
 * Read from the screens themselves, so a setting added to one is found by the
 * search without anybody remembering to list it.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'src/app/settings');
const OUT = join(ROOT, 'src/lib/settingsIndex.generated.ts');

// Not reachable by a row: Diagnostics is behind five taps on purpose.
const HIDDEN = new Set(['index', 'diagnostics']);

const SHOWN_ONLY = new Set(['LegendItem', 'PartLine', 'Field']);

const STRING = `(['"])((?:\\\\.|(?!\\1).)*)\\1`;
const unescape = (s) => s.replace(/\\(.)/g, '$1');
const all = (src, re) => [...src.matchAll(re)];

const screens = new Map();
for (const file of readdirSync(DIR).filter((f) => f.endsWith('.tsx')).sort()) {
  const name = file.replace(/\.tsx$/, '');
  screens.set(name, readFileSync(join(DIR, file), 'utf8'));
}

// Who opens whom. The index builds its routes from a list of keys.
const parent = new Map();
for (const [name, src] of screens) {
  const opened =
    name === 'index'
      ? all(src, /key: '([\w-]+)'/g).map((m) => m[1])
      : all(src, /\/settings\/([\w-]+)/g).map((m) => m[1]);
  for (const child of opened) if (screens.has(child) && !parent.has(child)) parent.set(child, name);
}

/** The screen's own title: the last string of its `title=`, which for a title
 *  that depends on the profile is the server's. */
function titleOf(name) {
  const src = screens.get(name);
  const expr = src.match(/<(?:SettingsPage|ScreenHeader) title=\{([^\n]*)\}/)?.[1];
  const found = expr ? all(expr, new RegExp(`t\\(${STRING}\\)`, 'g')) : [];
  return found.length > 0 ? unescape(found[found.length - 1][2]) : null;
}

const entries = [];
for (const [name, src] of screens) {
  if (HIDDEN.has(name)) continue;
  const path = [];
  for (let at = name; at && at !== 'index'; at = parent.get(at)) path.unshift(at);
  // Reached from the index, or it is not a place a result can lead to.
  if (parent.get(path[0]) !== 'index') continue;
  const titles = path.map(titleOf);
  if (titles.some((t) => !t)) continue;
  // The category itself, so its name finds it.
  if (path.length === 1) entries.push({ label: titles[0], screen: name, root: name, path: [] });
  const opens = new Map(
    [...parent].filter(([, p]) => p === name).map(([child]) => [titleOf(child), child]),
  );
  const seen = new Set();
  for (const m of all(src, new RegExp(`label(?:=\\{|:)\\s*t\\(\\s*${STRING}`, 'g'))) {
    // A choice inside a selector, not a setting: `{ value: …, label: … }`.
    const before = src.slice(0, m.index).split('\n');
    const line = before[before.length - 1];
    const prev = (before[before.length - 2] ?? '').trim();
    if (/value:/.test(line) || prev.startsWith('value:')) continue;
    // A figure being shown, not something to set.
    const tag = src.slice(0, m.index).match(/<(\w+)(?![\s\S]*<\w)/)?.[1];
    if (m[0].startsWith('label=') && SHOWN_ONLY.has(tag)) continue;
    const label = unescape(m[2]);
    if (seen.has(label)) continue;
    seen.add(label);
    // A row that only opens another screen leads straight to it.
    entries.push({ label, screen: opens.get(label) ?? name, root: path[0], path: titles });
  }
}

const text = `// Generated by scripts/settings-index.mjs. Do not edit: run \`pnpm settings:index\`.

export interface SettingEntry {
  /** The row's label, in English: the key the translations go by. */
  label: string;
  /** The screen it is on, under /settings. */
  screen: string;
  /** The category on the Settings index that leads to it. */
  root: string;
  /** Titles of the screens on the way there, in English. */
  path: string[];
}

export const SETTINGS_INDEX: SettingEntry[] = ${JSON.stringify(entries, null, 2)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== text) {
    console.error('src/lib/settingsIndex.generated.ts is out of date. Run: pnpm settings:index');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`${entries.length} settings on ${new Set(entries.map((e) => e.screen)).size} screens`);
}
